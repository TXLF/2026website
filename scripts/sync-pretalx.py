class Writer:
    def __init__(self, check: bool):
        self.check = check
        self.changed: list[str] = []
        self.adopted: list[str] = []
        self.orphaned: list[str] = []
        self.deleted: list[str] = []

    def delete(self, path: pathlib.Path) -> None:
        self.deleted.append(path.relative_to(REPO).as_posix())
        if not self.check:
            path.unlink()

    def write(self, path: pathlib.Path, content: str) -> None:
        rel = path.relative_to(REPO).as_posix()
        if path.exists() and path.read_text(encoding="utf-8") == content:
            return
        self.changed.append(rel)
        if not self.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")


def write_schedule_data(writer: Writer, sessions: list[dict], rooms: list[str]) -> None:
    days: dict[int, dict] = {}
    for session in sessions:
        days.setdefault(
            session["day_index"],
            {"date": session["date"], "items": []},
        )["items"].append(session)

    start_hour = min(s["start_hour"] for s in sessions)
    end_hour = max(s["end_hour"] + (1 if s["end_minute"] else 0) for s in sessions)

    lines = [GENERATED_HEADER]
    lines.append(f"start_hour: {start_hour}")
    lines.append(f"end_hour: {end_hour}")
    lines.append("rooms:")
    for room in rooms:
        lines.append(f"  - {y(room)}")
    lines.append("tablist:")

    for index in sorted(days):
        day = days[index]
        lines.append(f"  - name: {y(f'Day {index}')}")
        lines.append(f"    date: {y(day['date'].strftime('%A, %B %-d'))}")
        lines.append("    tablist_items:")
        for session in day["items"]:
            names = " & ".join(speaker_name(p) for p in session["persons"])
            person = session["persons"][0] if session["persons"] else None
            speaker_link = f"speakers/{speaker_slug(person)}/" if person else ""
            speaker_image = (person.get("avatar") or "") if person else ""
            talk_link = f"talks/{session['slug']}/" if session["slug"] else ""
            lines += [
                f"      - subject: {y(session['title'])}",
                f"        speaker: {y(names)}",
                f"        speaker_link: {y(speaker_link)}",
                f"        speaker_image: {y(speaker_image)}",
                f"        talk_link: {y(talk_link)}",
                f"        venue: {y(session['room'])}",
                f"        column: {rooms.index(session['room']) + 2}",
                f"        time: {y(session['time'])}",
                f"        start_hour: {session['start_hour']}",
                f"        start_minute: {session['start_minute']}",
                f"        end_hour: {session['end_hour']}",
                f"        end_minute: {session['end_minute']}",
                f"        type: {y(session['type'])}",
                f"        pretalx_code: {y(session['code'])}",
            ]

    writer.write(REPO / "data" / "schedule.yml", "\n".join(lines) + "\n")


def write_room_pages(writer: Writer, sessions: list[dict], rooms: list[str]) -> None:
    day_indexes = sorted({s["day_index"] for s in sessions})
    expected = {
        f"{slugify(room)}-schedule-day-{day}.md" for room in rooms for day in day_indexes
    } | {f"grid-schedule-day-{day}.md" for day in day_indexes}
    for path in sorted((REPO / "content").glob("*-schedule-day-*.md")):
        if path.name in expected:
            continue
        if owned(path) and path.exists():
            writer.delete(path)
        else:
            writer.orphaned.append(path.relative_to(REPO).as_posix())

    # All-rooms grid, one page per day, for signage and the big screen.
    for day_index in day_indexes:
        writer.write(
            REPO / "content" / f"grid-schedule-day-{day_index}.md",
            "\n".join(
                [
                    "---",
                    'type: "schedule"',
                    'layout: "full-page-grid-schedule"',
                    f"title: {y(f'Schedule Day {day_index} - Texas Linux Fest {YEAR}')}",
                    f"tabnum: {day_index - 1}",
                    "pretalx_managed: true",
                    "---",
                    "",
                ]
            ),
        )

    for room in rooms:
        for day_index in day_indexes:
            slug = slugify(room)
            path = REPO / "content" / f"{slug}-schedule-day-{day_index}.md"
            content = "\n".join(
                [
                    "---",
                    'type: "schedule"',
                    'layout: "room-schedule"',
                    f"title: {y(f'{room} Schedule Day {day_index} - Texas Linux Fest {YEAR}')}",
                    f"tabnum: {day_index - 1}",
                    f"venue: {y(room)}",
                    "pretalx_managed: true",
                    "---",
                    "",
                ]
            )
            # Room pages hold no editorial content -- only the room name, day
            # index, and layout -- so the sync owns them outright.
            writer.write(path, content)


def write_talk_pages(writer: Writer, sessions: list[dict]) -> None:
    for session in sessions:
        if not session["slug"]:
            continue

        when = "{}, {} {}, {}".format(
            session["date"].strftime("%A"),
            session["date"].strftime("%B"),
            session["date"].day,
            session["time"],
        )

        front = [
            "---",
            f"title: {y(session['title'])}",
            f"description: {y(f'Texas Linux Fest {YEAR}')}",
            f"page_header_bg: {y(PAGE_HEADER_BG)}",
            f"format: {y(session['type'])}",
            f"when: {y(when)}",
            f"where: {y(session['room'])}",
            f"pretalx_code: {y(session['code'])}",
            f"pretalx_link: {y(session['url'])}",
            "pretalx_managed: true",
        ]
        if session["track"]:
            front.append(f"track: {y(session['track'])}")
        if session["persons"]:
            front.append("")
            front.append("speakers:")
            for person in session["persons"]:
                front += [
                    f"  - name: {y(speaker_name(person))}",
                    f"    image: {y(person.get('avatar') or '')}",
                    f"    link: {y(f'speakers/{speaker_slug(person)}/')}",
                ]
        front.append("---")

        body = [""]
        if session["subtitle"]:
            body += [f"##### {session['subtitle']}", ""]
        if session["abstract"]:
            body += [markdown_paragraphs(session["abstract"]), ""]
        if session["description"] and session["description"] != session["abstract"]:
            body += [markdown_paragraphs(session["description"]), ""]

        path = REPO / "content" / "talks" / f"{session['slug']}.md"
        writer.write(path, "\n".join(front + body))


def front_matter_value(path: pathlib.Path, key: str) -> str | None:
    match = re.search(rf"^{key}:\s*(.+)$", path.read_text(encoding="utf-8")[:2000], re.MULTILINE)
    return unquote(match.group(1)) if match else None


def prune_talk_pages(writer: Writer, sessions: list[dict]) -> None:
    """Remove managed talk pages that no longer match a scheduled session.

    Covers both a withdrawn session and a retitled one, which lands at a new slug
    and would otherwise leave the old page live forever. Hand-written pages (no
    `pretalx_managed`) are the archive and stay.
    """
    live = {s["code"]: s["slug"] for s in sessions if s["slug"]}
    for path in sorted((REPO / "content" / "talks").glob("*.md")):
        if not owned(path):
            continue
        code = front_matter_value(path, "pretalx_code")
        # gone from the schedule, or retitled so it now lives at a different slug
        if code and live.get(code) != path.stem:
            writer.delete(path)


def stale_link(link: str, live_links: set[str]) -> bool:
    """True if a talk link on a speaker page points at a page we are removing."""
    if link in live_links:
        return False
    slug = link.strip("/").split("/")[-1]
    # owned() is True for a managed page we are pruning, and for one already gone;
    # False for a hand-written archive page, which we leave linked.
    return owned(REPO / "content" / "talks" / f"{slug}.md")


def prune_speaker_pages(writer: Writer, sessions: list[dict], touched: set[str]) -> None:
    """Clean up speaker pages for people who left the schedule.

    A speaker whose only session was withdrawn is not visited by
    write_speaker_pages at all, so their page keeps a dead talk link and stays
    listed as a current speaker until something sweeps it.
    """
    live_links = {f"talks/{s['slug']}/" for s in sessions if s["slug"]}
    for path in sorted((REPO / "content" / "speakers").glob("*.md")):
        rel = path.relative_to(REPO).as_posix()
        if rel in touched or not front_matter_value(path, "pretalx_code"):
            continue
        if owned(path):
            writer.delete(path)
            continue

        # hand-written page: drop this year's dead links and the current flag
        front, body = split_front_matter(path.read_text(encoding="utf-8"))
        talks = [t for t in existing_talk_links(front) if not stale_link(t[1], live_links)]
        front = strip_block(strip_block(strip_block(front, "talks"), "current"), "pretalx_code")
        while front and not front[-1].strip():
            front.pop()
        if talks:
            front.append("")
            front.append("talks:")
            for title, link in talks:
                front += [f"  - title: {y(title)}", f"    link: {y(link)}"]
        writer.write(path, "\n".join(["---"] + front + ["---"]) + body)


def write_speaker_pages(writer: Writer, sessions: list[dict], speakers_api: dict) -> set[str]:
    bios = {s["code"]: s for s in speakers_api}
    live_links = {f"talks/{s['slug']}/" for s in sessions if s["slug"]}
    touched: set[str] = set()

    people: dict[str, dict] = {}
    for session in sessions:
        for person in session["persons"]:
            entry = people.setdefault(person["code"], {"person": person, "talks": []})
            if session["slug"]:
                entry["talks"].append((session["title"], session["slug"]))

    for code, entry in sorted(people.items()):
        person = entry["person"]
        name = speaker_name(person)
        biography = (person.get("biography") or bios.get(code, {}).get("biography") or "").strip()
        avatar = person.get("avatar") or bios.get(code, {}).get("avatar_url") or ""
        path = REPO / "content" / "speakers" / f"{speaker_slug(person)}.md"
        new_talks = [(title, f"talks/{slug}/") for title, slug in entry["talks"]]

        if path.exists() and not owned(path):
            # A returning speaker with a hand-written page (bio, photo, social
            # links, past talks). Keep all of it -- only add this year's talks and
            # the flags that put them back on the speakers page.
            old_front, body = split_front_matter(path.read_text(encoding="utf-8"))
            merged = [
                talk for talk in existing_talk_links(old_front)
                if not stale_link(talk[1], live_links)
            ]
            for talk in new_talks:
                if talk[1] not in {link for _, link in merged}:
                    merged.append(talk)
            front = old_front
            for key in ("talks", "current", "pretalx_code"):
                front = strip_block(front, key)
            # drop a pretalx speaker link only to re-add it in a fixed position,
            # so a second run does not reshuffle the front matter; a hand-written
            # link pointing somewhere else is left exactly where the author put it
            url = person.get("url") or ""
            has_own_link = any(
                re.match(r"^link\s*:", line) and unquote(line.split(":", 1)[1]) != url
                for line in front
            )
            front = [line for line in front if not re.match(r"^link\s*:", line)] if not has_own_link else front
            while front and not front[-1].strip():
                front.pop()
            if url and not has_own_link:
                front.append(f"link: {y(url)}")
            front.append("current: true")
            front.append(f"pretalx_code: {y(code)}")
            new_talks = merged
            writer.adopted.append(path.relative_to(REPO).as_posix())
            front = ["---"] + front
        else:
            front = [
                "---",
                f"title: {y(name)}",
                f"description: {y(f'Texas Linux Fest {YEAR}')}",
                f"page_header_bg: {y(PAGE_HEADER_BG)}",
                f"image: {y(avatar)}",
                f"link: {y(person.get('url') or '')}",
                "current: true",
                f"pretalx_code: {y(code)}",
                "pretalx_managed: true",
            ]
            body = "\n\n" + markdown_paragraphs(biography) + "\n" if biography else "\n"

        if new_talks:
            front.append("")
            front.append("talks:")
            for title, link in new_talks:
                front += [
                    f"  - title: {y(title)}",
                    f"    link: {y(link)}",
                ]
        front.append("---")

        writer.write(path, "\n".join(front) + body)
        touched.add(path.relative_to(REPO).as_posix())

    return touched


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report what would change without writing; exit 1 if anything differs",
    )
    args = parser.parse_args()

    schedule = fetch(SCHEDULE_URL)
    speakers_api = fetch(SPEAKERS_URL)["results"]

    sessions = build_sessions(schedule)
    if not sessions:
        print("pretalx returned no scheduled sessions; refusing to write.", file=sys.stderr)
        return 2

    seen = list(dict.fromkeys(s["room"] for s in sessions))
    rooms = [r for r in ROOM_ORDER if r in seen] + [r for r in seen if r not in ROOM_ORDER]

    renamed = assign_talk_slugs(sessions)

    writer = Writer(check=args.check)
    write_schedule_data(writer, sessions, rooms)
    write_room_pages(writer, sessions, rooms)
    write_talk_pages(writer, sessions)
    prune_talk_pages(writer, sessions)
    touched = write_speaker_pages(writer, sessions, speakers_api)
    prune_speaker_pages(writer, sessions, touched)

    print(f"{len(sessions)} sessions across {len(rooms)} rooms: {', '.join(rooms)}")

    if writer.adopted:
        print("\nMerged into hand-written pages (bio, photo, and social links kept):")
        for path in sorted(writer.adopted):
            print(f"  {path}")

    if renamed:
        print("\nTalk slugs changed to avoid overwriting a hand-written page:")
        for line in sorted(renamed):
            print(f"  {line}")

    if writer.deleted:
        verb = "would delete" if args.check else "deleted"
        print(f"\n{verb} {len(writer.deleted)} files no longer on the schedule:")
        for path in sorted(writer.deleted):
            print(f"  {path}")

    if writer.orphaned:
        print("\nRoom pages with no matching pretalx room (delete by hand if stale):")
        for path in sorted(writer.orphaned):
            print(f"  {path}")

    if writer.changed:
        verb = "would change" if args.check else "wrote"
        print(f"\n{verb} {len(writer.changed)} files:")
        for path in sorted(writer.changed):
            print(f"  {path}")
    else:
        print("\nUp to date.")

    return 1 if (args.check and (writer.changed or writer.deleted)) else 0


if __name__ == "__main__":
    sys.exit(main())

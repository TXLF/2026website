#!/usr/bin/env python3
"""Sync the published pretalx schedule into this Hugo site.

Reads two public pretalx endpoints (no auth required):

  * https://pretalx.com/<event>/schedule/export/schedule.json  -- sessions, rooms, times
  * https://pretalx.com/api/events/<event>/speakers/           -- speaker bios and avatars

and writes:

  * data/schedule.yml                     -- the grid data consumed by the schedule partials
  * content/<room>-schedule-day-N.md      -- one single-room page per room per day
  * content/talks/<slug>.md               -- one page per session
  * content/speakers/<slug>.md            -- one page per speaker

Files this script generates outright carry `pretalx_managed: true` in their front
matter, and only those are ever rewritten wholesale. A hand-written page (the 2024
archive, Carl's featured speaker pages) is never clobbered: a speaker page gets
this year's talks merged into it and keeps its bio, photo, and social links, and a
talk page whose slug collides is given a distinct slug instead. Both cases are
reported at the end of the run.

Usage:
    python3 scripts/sync-pretalx.py            # write files
    python3 scripts/sync-pretalx.py --check    # exit 1 if anything would change
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import sys
import urllib.request

EVENT = "txlf2026"
YEAR = "2026"
SCHEDULE_URL = f"https://pretalx.com/{EVENT}/schedule/export/schedule.json"
SPEAKERS_URL = f"https://pretalx.com/api/events/{EVENT}/speakers/"

REPO = pathlib.Path(__file__).resolve().parent.parent

# Cosmetic left-to-right ordering of columns in the multi-room grid. Rooms that
# pretalx reports but that are not listed here are appended in the order they
# first appear in the schedule, so a new room never gets dropped.
ROOM_ORDER = ["Atrium", "Big Tex", "Lil Tex", "Balcones", "Stadium", "Bevo"]

# Some speakers use a handle in pretalx but already have a page under their real
# name from a previous year. Map pretalx speaker code -> (content slug, display
# name) so we link to the established page instead of creating a duplicate, and
# so the grid and the speaker page agree on the name.
SPEAKER_OVERRIDES = {
    "M3EXWD": ("alex-juarez", "Alex Juarez"),              # mrjandro
    "VZHNNV": ("carl-perry", "Carl Perry"),                # edolnx
    "BTDC83": ("christopher-hobbs", "Christopher Hobbs"),  # Hobbs
}

GENERATED_HEADER = (
    "# Generated by scripts/sync-pretalx.py from the published pretalx schedule.\n"
    "# Do not edit by hand -- your changes will be overwritten on the next sync.\n"
    "# Editorial copy (title, intro text, enable flag) lives in data/homepage.yml.\n"
)

PAGE_HEADER_BG = "images/background/page-title-bg.jpg"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #

def fetch(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "txlf-website-sync"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.load(resp)


def slugify(value: str) -> str:
    """Approximate Hugo's urlize: drop apostrophes, then non-alphanumerics to dashes."""
    value = value.replace("’", "").replace("'", "")
    value = re.sub(r"[^a-zA-Z0-9]+", "-", value)
    return value.strip("-").lower()


def y(value) -> str:
    """Render a scalar as YAML. JSON is a YAML subset, so json.dumps is always safe."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    return json.dumps(value if value is not None else "", ensure_ascii=False)


def markdown_paragraphs(text: str) -> str:
    """pretalx stores line breaks as single newlines; markdown needs blank lines."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return re.sub(r"\n(?!\n)", "\n\n", text).strip()


def parse_hhmm(value: str) -> tuple[int, int]:
    hour, minute = value.split(":")[:2]
    return int(hour), int(minute)


def owned(path: pathlib.Path) -> bool:
    """True if the file does not exist, or exists and is wholly generated by us.

    Merged speaker pages deliberately do NOT carry `pretalx_managed`, so a second
    run merges into them again rather than overwriting the hand-written parts.
    """
    if not path.exists():
        return True
    head = path.read_text(encoding="utf-8")[:2000]
    return re.search(r"^pretalx_managed:", head, re.MULTILINE) is not None


def split_front_matter(text: str) -> tuple[list[str], str]:
    """Split a Hugo markdown file into its front matter lines and its body."""
    if not text.startswith("---"):
        return [], text
    parts = text[3:].split("\n---", 1)
    if len(parts) < 2:
        return [], text
    front = parts[0].split("\n")[1:]
    body = parts[1].lstrip("-")
    return front, body


def strip_block(front: list[str], key: str) -> list[str]:
    """Drop a top-level `key:` line and any indented lines that belong to it."""
    out, dropping = [], False
    for line in front:
        if re.match(rf"^{key}\s*:", line):
            dropping = True
            continue
        if dropping:
            if line.strip() == "" or line.startswith((" ", "\t", "-")):
                continue
            dropping = False
        out.append(line)
    return out


def unquote(value: str) -> str:
    """Read back a scalar we (or a human) wrote, quoted or bare."""
    value = value.strip()
    if value.startswith('"'):
        try:
            return json.loads(value)
        except ValueError:
            return value.strip('"')
    return value.strip("'")


def existing_talk_links(front: list[str]) -> list[tuple[str, str]]:
    """Pull (title, link) pairs out of an existing `talks:` front matter block."""
    talks, in_block, title = [], False, None
    for line in front:
        if re.match(r"^talks\s*:", line):
            in_block = True
            continue
        if not in_block:
            continue
        if line.strip() and not line.startswith((" ", "\t", "-")):
            break
        title_match = re.match(r"\s*-\s*title\s*:\s*(.+?)\s*$", line)
        link_match = re.match(r"\s*link\s*:\s*(.+?)\s*$", line)
        if title_match:
            title = unquote(title_match.group(1))
        elif link_match and title is not None:
            talks.append((title, unquote(link_match.group(1))))
            title = None
    return talks



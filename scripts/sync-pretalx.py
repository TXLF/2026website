def build_sessions(schedule: dict) -> list[dict]:
    """Flatten schedule.json into a list of session dicts, one per scheduled slot."""
    conference = schedule["schedule"]["conference"]
    sessions = []

    for day in conference["days"]:
        date = datetime.date.fromisoformat(day["date"])
        for room, slots in day["rooms"].items():
            for slot in slots:
                start_hour, start_minute = parse_hhmm(slot["start"])
                dur_hour, dur_minute = parse_hhmm(slot["duration"])
                end_total = start_hour * 60 + start_minute + dur_hour * 60 + dur_minute
                end_hour, end_minute = divmod(end_total, 60)

                persons = slot.get("persons") or []
                sessions.append(
                    {
                        "code": slot["code"],
                        "day_index": day["index"],
                        "date": date,
                        "room": room,
                        "title": slot["title"],
                        "subtitle": slot.get("subtitle") or "",
                        "type": slot.get("type") or "Session",
                        "track": slot.get("track") or "",
                        "abstract": (slot.get("abstract") or "").strip(),
                        "description": (slot.get("description") or "").strip(),
                        "url": slot.get("url") or slot.get("origin_url") or "",
                        "persons": persons,
                        "start_hour": start_hour,
                        "start_minute": start_minute,
                        "end_hour": end_hour,
                        "end_minute": end_minute,
                        "time": f"{start_hour}:{start_minute:02d} - {end_hour}:{end_minute:02d}",
                    }
                )

    sessions.sort(key=lambda s: (s["day_index"], s["start_hour"], s["start_minute"], s["room"]))
    return sessions


def speaker_name(person: dict) -> str:
    override = SPEAKER_OVERRIDES.get(person["code"])
    return override[1] if override else (person.get("public_name") or person["name"])


def speaker_slug(person: dict) -> str:
    override = SPEAKER_OVERRIDES.get(person["code"])
    return override[0] if override else slugify(speaker_name(person))


def assign_talk_slugs(sessions: list[dict]) -> list[str]:
    """Give every session that warrants a page a unique content/talks slug.

    Sessions with no speakers (Expo Hall, Lightning Talks, Closing Remarks, the
    After Party, and the Keynote until a speaker is assigned) get no page -- they
    still appear in the grid, as plain text. A slug that would collide with a
    hand-maintained page from a previous year gets the pretalx code appended
    rather than clobbering the archive.
    """
    taken: set[str] = set()
    renamed: list[str] = []
    for session in sessions:
        if not session["persons"]:
            session["slug"] = None
            continue

        slug = preferred = slugify(session["title"])
        path = REPO / "content" / "talks" / f"{slug}.md"
        if slug in taken or not owned(path):
            slug = f"{slug}-{YEAR}"
        if slug in taken or not owned(REPO / "content" / "talks" / f"{slug}.md"):
            slug = f"{slugify(session['title'])}-{session['code'].lower()}"
        taken.add(slug)
        if slug != preferred:
            renamed.append(f"{preferred} -> {slug}")
        session["slug"] = slug
    return renamed


